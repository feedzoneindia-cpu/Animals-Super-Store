/**
 * Interactive administrator (superuser) creation CLI.
 *
 *   npm run create-admin          # from the project root
 *
 * Prompts for name, email, password and a confirmation, then creates one User
 * carrying the project's ADMIN role.
 *
 * Everything here deliberately reuses existing building blocks — the User
 * model (and its bcrypt pre-save hook), the shared MongoDB connection helper,
 * and the register validation schema — so no password hashing, validation, or
 * authentication logic is duplicated. This script only ever writes a
 * document: there is no public admin-registration API and nothing here can
 * issue a session.
 *
 * The plaintext password is never printed and never persisted; the model
 * hashes it with bcrypt (12 rounds) before it reaches MongoDB. The _id is
 * generated by Mongoose.
 */
import mongoose from 'mongoose';
import readline from 'node:readline';
import { connectDatabase } from '../config/db.js';
import User from '../models/User.js';
import { registerSchema } from '../validators/auth.validator.js';

/** The role value the User model accepts for administrators. */
const ADMIN_ROLE = 'ADMIN';

const IS_TERMINAL = Boolean(process.stdin.isTTY && process.stdout.isTTY);

/**
 * Sequential line reader.
 *
 * `rl.question()` is unusable here: on a piped (non-terminal) stdin readline
 * emits every line in one burst, and any line arriving before the next
 * question is registered is silently dropped. Buffering 'line' events
 * ourselves keeps prompt order correct for an interactive terminal and for
 * piped input alike.
 */
function createLineReader(rl) {
  const buffered = [];
  const waiters = [];
  let ended = false;

  rl.on('line', (line) => {
    if (waiters.length > 0) waiters.shift()(line);
    else buffered.push(line);
  });
  rl.on('close', () => {
    ended = true;
    while (waiters.length > 0) waiters.shift()(null);
  });

  return () => {
    if (buffered.length > 0) return Promise.resolve(buffered.shift());
    if (ended) return Promise.resolve(null);
    return new Promise((resolve) => waiters.push(resolve));
  };
}

/**
 * Prints a prompt and waits for one trimmed line.
 *
 * `hidden` suppresses echo for the password fields, so the plaintext never
 * lands on screen, in terminal scrollback, or in a CI log. On a piped stdin
 * readline is non-terminal and echoes nothing anyway.
 */
async function prompt(next, rl, label, { hidden = false } = {}) {
  process.stdout.write(`${label}: `);
  const original = rl._writeToOutput;
  if (hidden) rl._writeToOutput = () => {};

  try {
    const line = await next();
    if (line === null) {
      throw new Error('Input ended before every question was answered. Nothing was created.');
    }
    return line.trim();
  } finally {
    if (hidden) rl._writeToOutput = original;
    // A terminal already echoes the newline for visible input; a muted or
    // piped prompt needs it written explicitly.
    if (hidden || !IS_TERMINAL) process.stdout.write('\n');
  }
}

/** Reports zod issues the same way the API's validate middleware does. */
function reportIssues(error) {
  for (const issue of error.issues) {
    console.error(`[create-admin]   - ${issue.path.join('.') || 'input'}: ${issue.message}`);
  }
}

async function createAdmin() {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
    // Echo and prompt redrawing only make sense on a real terminal.
    terminal: IS_TERMINAL,
  });
  const next = createLineReader(rl);

  let admin;
  try {
    console.log('[create-admin] Create an Animals Super Store administrator');
    console.log('');

    const name = await prompt(next, rl, 'Name');
    const email = await prompt(next, rl, 'Email');
    const password = await prompt(next, rl, 'Password', { hidden: true });
    const confirmation = await prompt(next, rl, 'Confirm Password', { hidden: true });
    console.log('');

    if (password !== confirmation) {
      console.error('[create-admin] Passwords do not match. Nothing was created.');
      process.exitCode = 1;
      return;
    }

    // The same rules the public registration endpoint enforces, so the CLI
    // cannot create an account the API itself would reject. Checked before
    // connecting so bad input fails fast without touching the database.
    const parsed = registerSchema.safeParse({ name, email, password });
    if (!parsed.success) {
      console.error('[create-admin] Validation failed:');
      reportIssues(parsed.error);
      process.exitCode = 1;
      return;
    }

    const { name: safeName, email: safeEmail } = parsed.data;

    await connectDatabase();

    // An existing account is reported, never silently promoted or overwritten.
    const existing = await User.findOne({ email: safeEmail });
    if (existing) {
      if (existing.role === ADMIN_ROLE) {
        console.error(
          `[create-admin] An admin with the email ${safeEmail} already exists. Nothing was created.`
        );
      } else {
        console.error(
          `[create-admin] The email ${safeEmail} is already registered to a ${existing.role} account. ` +
            'Refusing to promote an existing account — use a different email.'
        );
      }
      process.exitCode = 1;
      return;
    }

    // User.create triggers the model's pre-save hook, which bcrypt-hashes the
    // password. Mongoose generates the _id. Plaintext is never stored.
    admin = await User.create({
      name: safeName,
      email: safeEmail,
      password: parsed.data.password,
      role: ADMIN_ROLE,
    });
  } catch (error) {
    console.error(`[create-admin] ${error.message}`);
    process.exitCode = 1;
    return;
  } finally {
    rl.close();
  }

  console.log(`[create-admin] Admin created: ${admin.name} <${admin.email}>`);
  console.log(`[create-admin] Role: ${admin.role} · id: ${admin._id}`);
  console.log('[create-admin] Password stored as a bcrypt hash; the plaintext was not saved or displayed.');
}

createAdmin()
  .catch((error) => {
    console.error(`[create-admin] Failed: ${error.message}`);
    process.exitCode = 1;
  })
  .finally(() => mongoose.disconnect());
